"""Seed the recipes' golden cases from the generator's expected verdicts (AU-hartland P2 · S2.2 T6).

    uv run scripts/seed-goldens.py                  # write automation/<recipe>/tests/<case>.yaml for the us world
    uv run scripts/seed-goldens.py --world cz       # <case>.cz.yaml (P3 · S3.3 T5)
    uv run scripts/seed-goldens.py --check          # exit 3 when a committed seed differs from what would be written

The source is `data/automation/expected/<world>/<recipe>.csv` (`key,route,verdict_reason_template,detail_count`, one
row per planted key and route — 50-expected.sql), the world's demo day is the header of
`data/automation/recon/R-A-<world>.md`, and the parameter values are the package's (`automation/automation.ttrm`).

One case per route, up to five keys each (contracts §7): `keys` are the debug run's port keys, `expected.verdicts`
every expected verdict of those keys — all their routes, so an overlapping recipe's second route is not reported as
an extra — and `detail_counts` where the CSV has them. A `none` route is a case too: its keys get NO verdict row.
A seed has no `pinned_from` (`ttrp conform` reports it as `seed`, D-89); `expected.actions` comes with the pinning
(P3). The CSV's `{fills}` stay in `verdict_reason` — the comparison fills them.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUTOMATION = ROOT / "automation"
EXPECTED = ROOT / "data" / "automation" / "expected"
RECON = ROOT / "data" / "automation" / "recon"
MAX_KEYS = 5

# recipe → its folder under automation/ (the recipe name is the file stem)
def recipe_files() -> dict[str, Path]:
    return {p.stem: p for p in sorted(AUTOMATION.rglob("*.ttrp")) if "stub" not in p.parts}


def recipe_parameters(ttrp: Path) -> list[str]:
    m = re.search(r"^\s*parameters:\s*\[([^\]]*)\]", ttrp.read_text(), re.M)
    return [p.strip() for p in m.group(1).split(",") if p.strip()] if m else []


def package_values() -> dict[str, str]:
    """`def parameter <n> { type: …, value: <v>, … }` → {n: v} (the value's source text)."""
    text = (AUTOMATION / "automation.ttrm").read_text()
    return dict(re.findall(r"def parameter\s+(\w+)\s*\{[^}]*?value:\s*([^,\s}]+)", text))


def world_as_of(world: str) -> str:
    head = (RECON / f"R-A-{world}.md").read_text().splitlines()[0]
    m = re.search(r"as of (\d{4}-\d{2}-\d{2})", head)
    if not m:
        raise SystemExit(f"no 'as of YYYY-MM-DD' in the header of R-A-{world}.md")
    return m.group(1)


def key_value(text: str) -> object:
    """`4711` → 4711; a composite key `1315:5` → [1315, 5] (the recipe's key order)."""
    parts = [int(p) if p.isdigit() else p for p in text.split(":")]
    return parts[0] if len(parts) == 1 else parts


def scalar(v: object) -> str:
    if isinstance(v, list):
        return "[" + ", ".join(scalar(x) for x in v) + "]"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str) and re.fullmatch(r"-?\d+(\.\d+)?", v):
        return v
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def case_name(route: str) -> str:
    return route.replace("_", "-")


def render_case(recipe: str, world: str, as_of: str, params: dict[str, str], route: str, rows: list[dict], source: Path | None = None) -> str:
    by_key: dict[str, list[dict]] = {}
    for r in rows:
        by_key.setdefault(r["key"], []).append(r)
    keys = [k for k in by_key if any(r["route"] == route for r in by_key[k])][:MAX_KEYS]
    lines = [
        f"# A seed — generated by scripts/seed-goldens.py from {source.relative_to(ROOT) if source else f'data/automation/expected/{world}/{recipe}.csv'}",
        "# (no pinned_from: `ttrp conform` reports it as a seed, D-89). Regenerate; do not edit.",
        f"case: {case_name(route)}",
        f"recipe: {recipe}",
        f"world: {world}",
        f'as_of: "{as_of}"',
        "parameters: { " + ", ".join(f"{n}: {v}" for n, v in params.items()) + " }" if params else "parameters: {}",
        "keys: [" + ", ".join(scalar(key_value(k)) for k in keys) + "]",
        "expected:",
    ]
    verdicts = [r for k in keys for r in by_key[k] if r["route"] != "none"]
    if not verdicts:
        lines.append("  verdicts: []                              # the keys get no verdict row")
    else:
        lines.append("  verdicts:")
        for r in verdicts:
            item = f"key: {scalar(key_value(r['key']))}, route: {r['route']}"
            if r["verdict_reason_template"]:
                item += f", verdict_reason: {scalar(r['verdict_reason_template'])}"
            lines.append(f"    - {{ {item} }}")
    details = [(k, r["detail_count"]) for k in keys for r in by_key[k] if r["detail_count"]]
    if details:
        lines.append("  detail_counts:")
        for k, d in details:
            counts = ", ".join(f"{c}: {n}" for c, n in (x.split(":") for x in d.split()))
            mapping_key = key_value(k)                      # a composite key is a quoted "a:b" here (a YAML key)
            lines.append(f"    {scalar(k) if isinstance(mapping_key, list) else scalar(mapping_key)}: {{ {counts} }}")
    if source and 'authoring-stubs' in source.parts:
        lines.insert(2, '# SYNTHETIC ops authoring fixture; not a served-world key or an observed run. Replace at Server P4 certification.')
    return "\n".join(lines) + "\n"


def seeds(world: str) -> dict[Path, str]:
    as_of = world_as_of(world)
    values = package_values()
    out: dict[Path, str] = {}
    for recipe, ttrp in recipe_files().items():
        source = EXPECTED / world / f"{recipe}.csv"
        if not source.exists() and 'ops' in ttrp.parts:
            source = ROOT / 'authoring-stubs/automation/ops/expected' / world / f'{recipe}.csv'
        if not source.exists():
            continue
        with source.open(newline="") as f:
            rows = list(csv.DictReader(f))
        params = {p: values[p] for p in recipe_parameters(ttrp)}
        suffix = "" if world == "us" else f".{world}"
        for route in dict.fromkeys(r["route"] for r in rows):
            out[ttrp.parent / "tests" / f"{case_name(route)}{suffix}.yaml"] = render_case(recipe, world, as_of, params, route, rows, source)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--world", default="us", choices=["us", "cz"])
    ap.add_argument("--check", action="store_true", help="exit 3 when a committed seed is stale or missing")
    args = ap.parse_args()
    want = seeds(args.world)
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in want.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("stale or missing seeds (run `uv run scripts/seed-goldens.py`):\n  " + "\n  ".join(stale), file=sys.stderr)
            return 3
        print(f"seed-goldens --check: {len(want)} seeds up to date ({args.world})")
        return 0
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"seed-goldens: wrote {len(want)} seeds ({args.world})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
